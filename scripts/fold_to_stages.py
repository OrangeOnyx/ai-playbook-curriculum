"""Fold the curriculum from five levels to four stages (spec 2026-09-17, Wave 3).

Pure functions: new_module_dir, new_file_path, rewrite_text, build_path_map, plan_moves.
`python scripts/fold_to_stages.py --dry-run` prints the move plan and the report.
`python scripts/fold_to_stages.py --apply` runs git mv for every move, rewrites the
mechanical text class in every Markdown file except the handwritten five and history/,
writes history/fold-map-2026-09.json (committed) and fold-report.md (not committed).
Idempotent: with no level-* folder left there is nothing to move and nothing to rewrite.
"""
import io, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

STAGE_OF_LEVEL = {
    "level-1-essentials": "1-starter",
    "level-2-intermediate": "2-intermediate",
    "level-3-advanced": "3-expert",
    "level-4-professional": "3-expert",
    "level-5-frontier": "4-frontier-operator",
}
STAGE_NUMBER = {"1-starter": 1, "2-intermediate": 2, "3-expert": 3, "4-frontier-operator": 4}
# Professional modules follow Advanced's inside Stage 3: number plus the Advanced count.
OFFSET = {("level-4-professional", "individual"): 14, ("level-4-professional", "company"): 10}
# Module folders whose own names carry the old numbering (before the offset is applied).
RENAME_MODULE = {
    "12-jargon-level-2": "12-jargon-stage-2",
    "14-jargon-level-3": "14-jargon-stage-3",
    "12-jargon-level-4": "12-jargon-stage-3-continued",
    "10-jargon-level-5": "10-jargon-stage-4",
}
RENAME_FILE = {
    "level-4-professional/eli10/what-is-a-model-card-eli10.md":
        "3-expert/eli10/what-is-a-model-card-for-your-own-model-eli10.md",
    "level-4-professional/README.md": "history/level-4-professional-README.md",
    "LEVEL-MAP.md": "STAGE-MAP.md",
    "GROUNDWORK-AND-FLUENCY.md": "PLAYBOOK-AND-CURRICULUM.md",
    "LEVELS-4-5-COMPLETION-SUMMARY.md": "history/LEVELS-4-5-COMPLETION-SUMMARY.md",
    "shared/graphics/hero-cover.png": "shared/graphics/hero-cover.svg",
    "shared/graphics/hero-level-1.png": "shared/graphics/stage-1.svg",
    "shared/graphics/hero-level-2.png": "shared/graphics/stage-2.svg",
    "shared/graphics/hero-level-3.png": "shared/graphics/stage-3.svg",
    "shared/graphics/hero-level-4.png": "shared/graphics/stage-3.svg",
    "shared/graphics/hero-level-5.png": "shared/graphics/stage-4.svg",
    "shared/graphics/level-map.svg": "shared/graphics/stage-map.svg",
}
# Graphics are regenerated by shared/graphics/render.py (Task 5); the fold deletes the old art.
DELETE = ["shared/graphics/hero-cover.png", "shared/graphics/hero-level-1.png",
          "shared/graphics/hero-level-2.png", "shared/graphics/hero-level-3.png",
          "shared/graphics/hero-level-4.png", "shared/graphics/hero-level-5.png",
          "shared/graphics/level-map.svg", "shared/graphics/program-flow.svg"]
# Rewritten by hand in Task 3 (new paths); the script moves but never edits them.
HANDWRITTEN = {"README.md", "STAGE-MAP.md", "PLAYBOOK-AND-CURRICULUM.md",
               "3-expert/README.md", "shared/graphics/README.md", "CONTRIBUTING.md"}
SKIP_TEXT_PREFIXES = ("history/",)

# Groundwork guide pages -> Playbook pages (the same table groundwork_redirects.py serves).
URL_MAP = [
    ("https://groundwork.adamabdalla.com/guide/identity.html", "https://playbook.adamabdalla.com/1-starter/1-1-know-me/"),
    ("https://groundwork.adamabdalla.com/guide/knowledge.html", "https://playbook.adamabdalla.com/2-intermediate/2-1-know-what-is-true/"),
    ("https://groundwork.adamabdalla.com/guide/remember.html", "https://playbook.adamabdalla.com/2-intermediate/2-2-remember-my-world/"),
    ("https://groundwork.adamabdalla.com/guide/limits.html", "https://playbook.adamabdalla.com/3-expert/3-1-know-your-limits/"),
    ("https://groundwork.adamabdalla.com/guide/operator.html", "https://playbook.adamabdalla.com/3-expert/3-2-help-me-operate/"),
    ("https://groundwork.adamabdalla.com/guide/improve.html", "https://playbook.adamabdalla.com/4-frontier-operator/4-2-improve-and-survive/"),
    ("https://groundwork.adamabdalla.com/curriculum/", "https://playbook.adamabdalla.com/curriculum/"),
    ("https://groundwork.adamabdalla.com/guide/", "https://playbook.adamabdalla.com/"),
    ("https://groundwork.adamabdalla.com", "https://playbook.adamabdalla.com"),
]
PHRASES = [  # ordered: ranges and long phrases before the single words that would eat them
    ("Levels 1 and much of Level 2", "Stage 1 and much of Stage 2"),   # field-guide-manifesto.md
    ("Levels 1 and 2", "Stages 1 and 2"), ("Levels 1-2", "Stages 1 and 2"), ("Levels 1–2", "Stages 1 and 2"),
    ("Levels 4 and 5", "Stages 3 and 4"), ("Levels 4-5", "Stages 3 and 4"), ("Levels 4–5", "Stages 3 and 4"),
    ("Level 1–3", "Stages 1 to 3"), ("Level 1-3", "Stages 1 to 3"), ("Levels 1–3", "Stages 1 to 3"), ("Levels 1-3", "Stages 1 to 3"),
    ("Level 3+", "Stage 3 and up"),
    ("level-3+", "Stage 3 and up"),
    ("five-level", "four-stage"), ("Five-level", "Four-stage"), ("five levels", "four stages"), ("Five levels", "Four stages"),
    ("The Groundwork Curriculum", "The AI Playbook Curriculum"), ("the Groundwork Curriculum", "The AI Playbook Curriculum"),
    ("Groundwork Curriculum", "The AI Playbook Curriculum"),
]
SINGLE = re.compile(r"\bLevel ([1-5])\b")
SINGLE_LOWER = re.compile(r"\blevel-([1-5])\b(?!-)")
SINGLE_MAP = {"1": "Stage 1", "2": "Stage 2", "3": "Stage 3", "4": "Stage 3", "5": "Stage 4"}
RESIDUAL = re.compile(r"\bGroundwork\b")


def new_module_dir(old_rel):
    level, track, mod = old_rel.split("/")
    stage = STAGE_OF_LEVEL[level]
    mod = RENAME_MODULE.get(mod, mod)
    off = OFFSET.get((level, track), 0)
    if off:
        num, _, rest = mod.partition("-")
        mod = "%02d-%s" % (int(num) + off, rest)
    return "%s/%s/%s" % (stage, track, mod)


def new_file_path(old_rel):
    if old_rel in RENAME_FILE:
        return RENAME_FILE[old_rel]
    parts = old_rel.split("/")
    if parts[0] not in STAGE_OF_LEVEL:
        return old_rel
    if len(parts) >= 4 and parts[1] in ("individual", "company"):
        return new_module_dir("/".join(parts[:3])) + "/" + "/".join(parts[3:])
    return STAGE_OF_LEVEL[parts[0]] + "/" + "/".join(parts[1:])


def build_path_map(root):
    """Every directory and renamed file, old -> new, longest keys first when applied."""
    pm = {}
    for level in STAGE_OF_LEVEL:
        ld = root / level
        if not ld.is_dir():
            continue
        pm[level] = STAGE_OF_LEVEL[level]
        for track in ("individual", "company"):
            td = ld / track
            if td.is_dir():
                for mod in sorted(p for p in td.iterdir() if p.is_dir()):
                    old = "%s/%s/%s" % (level, track, mod.name)
                    pm[old] = new_module_dir(old)
    pm.update(RENAME_FILE)
    return pm


def plan_moves(root):
    """(old, new) pairs for git mv, computed on the UNMOVED tree, in an order that never
    moves into a missing parent and never moves a path twice. The first level that maps
    to a stage moves whole; a second level mapping to the same stage (Professional into
    3-expert) merges file by file."""
    moves = []
    planned_stage = set()
    for level, stage in STAGE_OF_LEVEL.items():
        ld = root / level
        if not ld.is_dir():
            continue
        if not (root / stage).exists() and stage not in planned_stage:
            moves.append((level, stage))          # whole folder in one move
            planned_stage.add(stage)
            for track in ("individual", "company"):   # jargon folders inside it still carry the old name
                td = ld / track
                if td.is_dir():
                    for mod in sorted(p for p in td.iterdir() if p.is_dir()):
                        if mod.name in RENAME_MODULE:
                            moves.append(("%s/%s/%s" % (stage, track, mod.name),
                                          "%s/%s/%s" % (stage, track, RENAME_MODULE[mod.name])))
            continue
        for track in ("individual", "company"):   # merge into a stage folder that already exists (or is planned)
            td = ld / track
            if td.is_dir():
                for mod in sorted(p for p in td.iterdir() if p.is_dir()):
                    old = "%s/%s/%s" % (level, track, mod.name)
                    moves.append((old, new_module_dir(old)))
        for sub in ("shared", "eli10", "repos", "00-start-here"):
            sd = ld / sub
            if sd.is_dir():
                for f in sorted(sd.rglob("*")):
                    if f.is_file():
                        old = str(f.relative_to(root)).replace("\\", "/")
                        if old in RENAME_FILE:
                            continue              # already planned from RENAME_FILE (the ELI10 collision)
                        moves.append((old, new_file_path(old)))
    # RENAME_FILE moves run last: several target a stage directory (e.g. 3-expert/eli10/...)
    # that a whole-folder move above creates by renaming a level directory. mkdir-ing that
    # stage directory early (as part of one of these moves) would make git mv nest the later
    # whole-folder move inside it instead of renaming it, so these must not run first.
    for old, new in RENAME_FILE.items():
        if (root / old).exists() and old not in DELETE:
            moves.append((old, new))
    return moves


def rewrite_text(text, path_map, in_level4):
    for old, new in URL_MAP:
        text = text.replace(old, new)
    for old, new in PHRASES:
        text = text.replace(old, new)
    text = SINGLE.sub(lambda m: SINGLE_MAP[m.group(1)], text)
    for old in sorted(path_map, key=len, reverse=True):
        text = text.replace(old, path_map[old])
    # after path_map, not before: a bare "level-3" also sits inside untouched filenames
    # like "hero-level-3.png" that path_map's exact-string keys still need to see intact.
    text = SINGLE_LOWER.sub(lambda m: SINGLE_MAP[m.group(1)], text)
    if in_level4:
        for old, new in path_map.items():
            if old.startswith("level-4-professional/") and old.count("/") == 2:
                omod, nmod = old.rsplit("/", 1)[1], new.rsplit("/", 1)[1]
                text = re.sub(r"(?<![\w-])%s(?![\w-])" % re.escape(omod), nmod, text)
    hits = RESIDUAL.findall(text)
    return text, hits


def md_files(root):
    for p in sorted(root.rglob("*.md")):
        rel = str(p.relative_to(root)).replace("\\", "/")
        if rel.startswith(".git/") or rel.startswith(SKIP_TEXT_PREFIXES) or rel in HANDWRITTEN:
            continue
        yield p, rel


def main(argv):
    apply = "--apply" in argv
    pm = build_path_map(ROOT)
    moves = plan_moves(ROOT)
    report = ["# Fold report", "", "## Moves (%d)" % len(moves)] + ["- `%s` -> `%s`" % m for m in moves]
    if apply:
        for old, new in moves:
            (ROOT / new).parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(["git", "mv", old, new], cwd=ROOT, check=True)
        for rel in DELETE:
            if (ROOT / rel).exists():
                subprocess.run(["git", "rm", "-q", rel], cwd=ROOT, check=True)
        (ROOT / "history").mkdir(exist_ok=True)
        io.open(ROOT / "history" / "fold-map-2026-09.json", "w", encoding="utf-8", newline="\n").write(
            json.dumps({"levels": STAGE_OF_LEVEL, "paths": pm}, indent=1) + "\n")
    changed, residual = [], []
    for p, rel in md_files(ROOT):
        was_level4 = rel.startswith("3-expert/") and any(
            rel.startswith(v + "/") for k, v in pm.items() if k.startswith("level-4-professional/") and k.count("/") == 2)
        text = io.open(p, encoding="utf-8").read()
        new, hits = rewrite_text(text, pm, was_level4)
        if hits:
            residual.append("- `%s`: %d" % (rel, len(hits)))
        if new != text:
            changed.append("- `%s`" % rel)
            if apply:
                io.open(p, "w", encoding="utf-8", newline="\n").write(new)
    report += ["", "## Files rewritten (%d)" % len(changed)] + changed
    report += ["", "## Residual 'Groundwork' mentions, hand-edit in Task 3 (%d files)" % len(residual)] + residual
    io.open(ROOT / "fold-report.md", "w", encoding="utf-8", newline="\n").write("\n".join(report) + "\n")
    print("\n".join(report[:3]), "...", "\n".join(report[-len(residual) - 2:]))
    print("applied" if apply else "dry run; nothing written except fold-report.md")


if __name__ == "__main__":
    main(sys.argv[1:])
